export function airlinePhoto(airline, type) {
  const a = String(airline || '').toUpperCase(), t = String(type || '').toUpperCase();
  if (!/^[A-Z]{3}$/.test(a) || !t) return null;
  return hit(`${a}-${t}`) || (SIBLING[t] ? hit(`${a}-${SIBLING[t]}`) : null);
}
