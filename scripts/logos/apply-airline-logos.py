#!/usr/bin/env python3
"""Download the kept airline logos (2026-11-15): scripts/logos/candidates.json (status 'logo') minus rejects.json
({ICAO: reason}) -> assets/logos/<ICAO>.webp (Commons-rendered PNG, 256 px wide, transparent margins trimmed, lossless webp)
and js/airline-logos.js (AIRLINE_LOGOS {ICAO: {w, h, licence, source, title, dark?}} + airlineLogo(icao)).
dark: true = mostly white pixels, invisible on a white card, needs a dark backing (auto-detected; dark-overrides.json
{ICAO: true/false} wins after a look at the sheet).
Usage: python3 -I scripts/logos/apply-airline-logos.py [--force]"""
import io, json, os, sys, time, urllib.parse, urllib.request
from PIL import Image, PngImagePlugin
PngImagePlugin.MAX_TEXT_CHUNK = 64 * 1024 * 1024
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..', '..')
OUT = os.path.join(ROOT, 'assets', 'logos'); os.makedirs(OUT, exist_ok=True)
UA = 'SkyCollectorResearch/0.1 (https://github.com/sevaan/sky-collector)'
C = json.load(open(os.path.join(HERE, 'candidates.json')))
def jl(n):
    try: return json.load(open(os.path.join(HERE, n)))
    except Exception: return {}
REJ = jl('rejects.json'); DARK = jl('dark-overrides.json'); CACHE = os.path.join(HERE, '.cache'); os.makedirs(CACHE, exist_ok=True)
def fetch(file):
    url = 'https://commons.wikimedia.org/wiki/Special:FilePath/' + urllib.parse.quote(file.replace(' ', '_')) + '?width=256'
    for t in range(4):
        try: return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=60).read()
        except Exception as e: print(file, 'retry', e); time.sleep(4 + 4 * t)
def is_dark(im):
    a = im.getchannel('A'); n = im.width * im.height
    px = [p for p in im.getdata() if p[3] > 128]
    if not px or sum(1 for v in a.getdata() if v < 40) / n < 0.05: return False   # an opaque white box is fine on white
    return sum(1 for p in px if min(p[:3]) > 215) / len(px) > 0.6
meta = {}; n = 0
for code in sorted(C):
    r = C[code]
    if r['status'] != 'logo' or code in REJ: 
        p = os.path.join(OUT, code + '.webp')
        if os.path.exists(p) and code in REJ: os.remove(p)
        continue
    dest = os.path.join(OUT, code + '.webp'); raw = os.path.join(CACHE, code + '.png')
    if '--force' in sys.argv or not os.path.exists(raw):
        data = fetch(r['file'])
        if not data: print(code, 'download failed'); continue
        open(raw, 'wb').write(data); time.sleep(0.5); n += 1
    try: im = Image.open(raw).convert('RGBA')
    except Exception as e: print(code, 'bad image', e); continue
    bb = im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
    if not bb: print(code, 'empty'); continue
    im = im.crop(bb)
    if im.width > 256: im = im.resize((256, max(1, round(im.height * 256 / im.width))), Image.LANCZOS)
    im.save(dest, 'WEBP', lossless=True, method=6)
    meta[code] = {'w': im.width, 'h': im.height, 'licence': r['licence'], 'source': r['source'], 'title': r['title']}
    d = DARK.get(code, is_dark(im))
    if d: meta[code]['dark'] = True
body = json.dumps(meta, indent=1, ensure_ascii=False, sort_keys=True)
open(os.path.join(ROOT, 'js', 'airline-logos.js'), 'w').write(f'''// GENERATED by scripts/logos/apply-airline-logos.py, do not edit. Airline logos from Wikimedia Commons (Wikidata P154),
// public domain / CC0 only, shown beside the airline's name to say which airline it is. LOGOS_ENABLED is the one switch
// that hides every logo: airlineLogo() returns null while it is off.
export const AIRLINE_LOGOS = {body};
let enabled = true;
export function setLogosEnabled(on) {{ enabled = !!on; }}
export function logosEnabled() {{ return enabled; }}
/** ICAO airline code -> {{ url, w, h, licence, source, title, dark? }} or null (no logo, or logos switched off). */
export function airlineLogo(icao) {{
  const m = enabled && AIRLINE_LOGOS[String(icao || '').toUpperCase()];
  return m ? {{ url: new URL('../assets/logos/' + String(icao).toUpperCase() + '.webp', import.meta.url).href, ...m }} : null;
}}
''')
print(len(meta), 'logos;', n, 'downloaded; dark:', sum(1 for m in meta.values() if m.get('dark')))
