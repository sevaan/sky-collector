"""Write js/sky-tiers.js from the sample study (docs/DESIGN-LOOP.md §1, approved 2026-11-17): the aircraft types in order of
how much of the world's traffic they are (unique aircraft per place), so the game can say Common (top 15), Uncommon
(16-60) or Rare (the rest). Epic and Legendary are hand lists in js/sky-tiers.js's own header, kept by this script.
Usage: python3 -I scripts/research/build-tiers.py"""
import collections, glob, gzip, json, os
ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
EPIC = ['B741', 'B742', 'B743', 'B744', 'B748', 'B74S', 'B74R', 'B74D', 'BLCF', 'A388', 'A342', 'A343', 'A345', 'A346', 'MD11', 'DC10', 'C17', 'C130', 'C30J', 'C5M', 'A400',
        'K35R', 'K35E', 'KC10', 'E3TF', 'E3CF', 'E6', 'B52', 'B1', 'B2', 'P8', 'C2', 'AN12', 'IL76', 'IL96', 'C295', 'V22', 'U2', 'F16', 'F18', 'F35', 'F15', 'EUFI', 'A10', 'H47', 'H53']
LEGENDARY = ['A124', 'A3ST', 'A337', 'SHIP', 'BALL', 'DC3', 'B17', 'B29', 'LANC', 'SPIT', 'JU52', 'P51']
# Common light, business and regional types the sample under-counts (they fly low, out of a receiver's range): Uncommon,
# not Rare (aviation-enthusiast playtest 2026-11-19: "Rare Cessna 182"). E75S is the E175's other wing: Common, like E75L.
LIFT_UNCOMMON = ['E75S', 'C182', 'C206', 'C210', 'BE36', 'BE35', 'BE58', 'DA40', 'DA42', 'DA62', 'SR20', 'P28R', 'PA32', 'PA34', 'PA46', 'M20P', 'C150', 'CRJ2', 'AT72', 'AT75', 'AT45', 'B736', 'B712', 'B753', 'B762', 'B764', 'A318', 'E135', 'DH8C', 'DH8B', 'BE9L']
# Military types are Epic again (Sevaan 2026-11-19: caught by type, never by callsign, registration, unit or route). No retired types that can't be caught (A225 destroyed 2022, Concorde 2003, no airworthy Constellation).
lifted = set(EPIC) | set(LEGENDARY)
C = collections.Counter(); seen = set()
for f in sorted(glob.glob(os.path.join(ROOT, 'data', 'research', 'samples-*.jsonl.gz'))):
    for line in gzip.open(f, 'rt'):
        r = json.loads(line)
        for a in r['ac']:
            k = (r['place'], a[0])
            if k in seen or not a[2]: continue
            seen.add(k); C[a[2]] += 1
ranked = [t for t, _ in C.most_common() if t not in lifted]
n = sum(C.values()); share = lambda ts: round(100 * sum(C[t] for t in ts) / n, 1)
common, uncommon = ranked[:15], ranked[15:60]
if 'E75L' in common and 'E75S' not in common: common.append('E75S')  # one plane, two wing codes
uncommon += [t for t in LIFT_UNCOMMON if t not in common and t not in uncommon]
out = f"""// Aircraft type tiers (docs/DESIGN-LOOP.md §1, approved by Sevaan 2026-11-17). A card has one tier everywhere.
// Generated by scripts/research/build-tiers.py from the 24-hour sample study ({n:,} aircraft at 27 places): the 15
// most-seen types are Common ({share(common)}% of sightings), ranks 16-60 Uncommon ({share(uncommon)}%), every other type Rare.
// Epic and Legendary are hand lists (the ones people point at; edit them in the script): {share([t for t in EPIC if t in C])}% and {share([t for t in LEGENDARY if t in C])}%.
export const COMMON_TYPES = new Set({json.dumps(common)});
export const UNCOMMON_TYPES = new Set({json.dumps(uncommon)});
export const EPIC_TYPES = new Set({json.dumps(EPIC)});
export const LEGENDARY_TYPES = new Set({json.dumps(LEGENDARY)});
// heli: helicopters are Rare whatever the type (0-11% of traffic by place).
export function typeTier(type, heli = false) {{
  const t = String(type || '').toUpperCase();
  if (LEGENDARY_TYPES.has(t)) return 'legendary';
  if (EPIC_TYPES.has(t)) return 'epic';
  if (heli) return 'rare';
  if (COMMON_TYPES.has(t)) return 'common';
  if (UNCOMMON_TYPES.has(t)) return 'uncommon';
  return t ? 'rare' : 'common'; // no type code at all: an unknown aircraft is nothing special
}}
"""
open(os.path.join(ROOT, 'js', 'sky-tiers.js'), 'w').write(out)
print('common', common); print('uncommon', uncommon[:12], '…'); print('shares', share(common), share(uncommon), 'epic', share([t for t in EPIC if t in C]))
