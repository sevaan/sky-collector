// Build js/airlines.js: ICAO airline code -> name, for every airline-style callsign (3 letters + digit).
//   node scripts/build-airlines.mjs [path/to/airlines.csv]
// Source: Virtual Radar Server's standing data (CC0), airlines/schema-01/airlines.csv, the same repo js/routes.js reads.
// That file has no callsign word, country or active flag, so the table is just code -> name (about 5,900 airlines).
// The hand-typed list in js/planes.js (AIRLINES) overrides it: those names are nicer ("American", not "American Airlines").
import { readFileSync, writeFileSync } from 'node:fs';

const URL_CSV = 'https://raw.githubusercontent.com/vradarserver/standing-data/main/airlines/schema-01/airlines.csv';
const root = new URL('../', import.meta.url);

function parseCsv(txt) {
  const rows = []; let row = [], cell = '', q = false;
  for (let i = 0; i < txt.length; i++) {
    const c = txt[i];
    if (q) { if (c === '"') { if (txt[i + 1] === '"') { cell += '"'; i++; } else q = false; } else cell += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && txt[i + 1] === '\n') i++; row.push(cell); rows.push(row); row = []; cell = ''; }
    else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows;
}

/* the source has some names HTML-escaped ("D &amp; D Aviation") and some UTF-8 read as Latin-1 ("Hydro-QuÃ©bec"); QA 2026-11-19 */
const fixText = (s) => { let t = s.replace(/&amp;/g, '&').replace(/&#39;|&apos;/g, "'").replace(/&quot;/g, '"'); if (/Ã|Â/.test(t)) { const u = Buffer.from(t, 'latin1').toString('utf8'); if (!u.includes('\uFFFD')) t = u; } return t; };
const arg = process.argv[2];
const csv = (arg ? readFileSync(arg, 'utf8') : await (await fetch(URL_CSV)).text()).replace(/^﻿/, '');
const [head, ...rows] = parseCsv(csv).filter((r) => r.length > 1);
const iName = head.indexOf('Name'), iIcao = head.indexOf('ICAO');
const out = {};
for (const r of rows) {
  const icao = (r[iIcao] ?? '').trim().toUpperCase(), name = fixText((r[iName] ?? '').trim().replace(/\s+/g, ' '));
  if (/^[A-Z]{3}$/.test(icao) && name && !out[icao]) out[icao] = name;
}
const planes = readFileSync(new URL('js/planes.js', root), 'utf8');
const hand = planes.match(/const AIRLINES = \{([\s\S]*?)\};/)[1];
for (const [, k, v] of hand.matchAll(/([A-Z]{3}):\s*'([^']+)'/g)) out[k] = v;

const body = Object.keys(out).sort().map((k) => k + ':' + JSON.stringify(out[k])).join(',');
writeFileSync(new URL('js/airlines.js', root),
  '// GENERATED by scripts/build-airlines.mjs, do not edit. ICAO airline code -> name (Virtual Radar Server standing data, CC0,\n' +
  '// plus the hand list in planes.js as overrides). Loaded lazily by planes.js.\n' +
  'export const AIRLINE_NAMES = {' + body + '};\n');
console.log(Object.keys(out).length + ' airlines');
