#!/usr/bin/env python3
"""Researched facts for flight cards (2026-11-18, Sevaan: "Are there other facts flights could have too?" ... "Do all three").
Writer-researchers drafted up to three facts per airline (or airport) to docs/FACT-STYLE.md; independent fact-checkers
re-read every source and gave each fact ok / fix / drop. This merges them, like apply-type-facts.py does for aircraft:
  WORK/out-*.json   {CODE: [{fact, angle, source, checked}, ...], "_skipped": {CODE: why}}
  WORK/check-*.json {"CODE#n": {verdict, issue, fixed, evidence}}
-> js/airline-facts.js AIRLINE_FACTS (kind airline, ICAO airline codes) or js/airport-facts.js AIRPORT_FACTS (kind airport,
   ICAO airport codes), and docs/FACTS-SOURCES-AIRLINES.md / -AIRPORTS.md (one row per fact: code, n, fact, source, checked).
Existing entries for codes not in WORK are kept, so batches add up. Rules re-checked here: one **bold** pair, 60-200
characters, no banned words, no "Did you know", no "!".
Usage: python3 scripts/facts/apply-flight-facts.py airline|airport WORK_DIR"""
import glob, json, os, re, sys
KIND, WORK = sys.argv[1], sys.argv[2]
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
JS = os.path.join(ROOT, 'js', f'{KIND}-facts.js'); VAR = 'AIRLINE_FACTS' if KIND == 'airline' else 'AIRPORT_FACTS'
MD = os.path.join(ROOT, 'docs', f'FACTS-SOURCES-{KIND.upper()}S.md')
BANNED = re.compile(r'\b(crash(es|ed)?|accidents?|incidents?|hijack\w*|grounded|grounding|wars?|killed|bankrupt\w*|strikes?|lawsuits?)\b', re.I)
def ok(t): return (len(re.findall(r'\*\*[^*]+\*\*', t)) == 1 and t.count('**') == 2 and 60 <= len(t) <= 200
                   and not BANNED.search(t) and not re.search(r'did you know', t, re.I) and '!' not in t)
facts, skipped = {}, {}
for f in sorted(glob.glob(os.path.join(WORK, 'out-*.json'))):
    d = json.load(open(f)); skipped.update(d.pop('_skipped', {}) or {}); facts.update(d)
checks = {}
for f in sorted(glob.glob(os.path.join(WORK, 'check-*.json'))): checks.update(json.load(open(f)))
# what is there already (earlier batches)
old = {}
if os.path.exists(JS):
    m = re.search(VAR + r' = (\{.*\});', open(JS).read(), re.S)
    if m and m.group(1).strip() != '{}': old = json.loads(re.sub(r',(\s*[\]}])', r'\1', m.group(1)))
oldrows = []
if os.path.exists(MD): oldrows = [l for l in open(MD).read().splitlines() if l.startswith('| ') and not l.startswith('| Code')]
out, rows, problems, stats = dict(old), [], [], {'ok': 0, 'fix': 0, 'drop': 0, 'unchecked': 0}
cell = lambda x: str(x).replace('|', '\\|').replace('\n', ' ')
for code in sorted(facts):
    lst = []
    for i, e in enumerate(facts[code][:3], 1):
        c = checks.get(f'{code}#{i}'); text, src, note = e['fact'], e.get('source', ''), e.get('checked', '')
        if not c: stats['unchecked'] += 1; problems.append(f'{code}#{i}: not checked, left out'); continue
        v = c.get('verdict', 'ok'); stats[v] = stats.get(v, 0) + 1
        if v in ('fix', 'drop') and c.get('fixed'):
            text = c['fixed']; note = c.get('evidence') or note
            m = re.search(r'https?://\S+', c.get('evidence') or '')
            if m: src = m.group(0).rstrip(').,;')
        elif v == 'drop': problems.append(f'{code}#{i}: dropped'); continue
        text = text.strip()
        if not ok(text): problems.append(f'{code}#{i}: fails the rules: {text}'); continue
        if text in lst: continue
        lst.append(text); rows.append(f'| {code} | {i} | {cell(text)} | {cell(src)} | {cell(note)[:300]} |')
    if lst: out[code] = lst
    oldrows = [r for r in oldrows if not r.startswith(f'| {code} |')]
print(stats, len(out), KIND + 's', sum(len(v) for v in out.values()), 'facts; skipped by writers:', skipped)
for p in problems: print('  !', p)
body = ',\n'.join(f'  {k}: [\n' + ',\n'.join('    ' + json.dumps(t, ensure_ascii=False) for t in v) + ',\n  ]' for k, v in sorted(out.items()))
head = open(JS).read().split(f'export const {VAR}')[0]
open(JS, 'w').write(head + f'export const {VAR} = {{\n' + body + (',\n' if body else '') + '};\n')
md = [f'# {KIND.capitalize()} facts: sources', '',
      f'Facts on flight cards about {KIND}s (`js/{KIND}-facts.js`, shown by `js/flight-facts.js`), written to `docs/FACT-STYLE.md`.',
      'Each was checked by its writer-researcher and then independently by a fact-checker against the source below; "Checked" is what was read there.',
      'Generated by `scripts/facts/apply-flight-facts.py`.', '', '| Code | # | Fact | Source | Checked |', '|---|---|---|---|---|']
open(MD, 'w').write('\n'.join(md + sorted(oldrows + rows)) + '\n')
