#!/usr/bin/env python3
"""Three facts per aircraft type (2026-11-18, Sevaan: "a team of content writers and researchers ... more interesting facts
for these cards ... there may be multiple facts too"). Six writer-researchers drafted three facts per type (docs/FACT-STYLE.md),
three independent fact-checkers re-read every source and gave each fact ok / fix / drop. This merges them:
  WORK/out-*.json   {CODE: [{fact, angle, source, checked, kept, note?} x3]}
  WORK/check-*.json {"CODE#n": {verdict, issue, fixed, evidence}}
-> js/sky-facts.js TYPE_FACTS {CODE: [fact1, fact2, fact3]} (fact 1 first: the one a new card shows) and
   docs/FACTS-SOURCES.md (one row per fact: code, n, fact, source, what was checked).
Rules re-checked here: one **bold** pair, 60-200 characters, no banned words, no "Did you know", no "!".
Usage: python3 scripts/facts/apply-type-facts.py WORK_DIR"""
import glob, json, os, re, sys
WORK = sys.argv[1]; ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
BANNED = re.compile(r'\b(crash(es|ed)?|accidents?|grounded|grounding|wars?|killed)\b', re.I)
facts = {}
for f in sorted(glob.glob(os.path.join(WORK, 'out-*.json'))): facts.update(json.load(open(f)))
checks = {}
for f in sorted(glob.glob(os.path.join(WORK, 'check-*.json'))): checks.update(json.load(open(f)))
def ok(t): return (len(re.findall(r'\*\*[^*]+\*\*', t)) == 1 and t.count('**') == 2 and 60 <= len(t) <= 200
                   and not BANNED.search(t) and not re.search(r'did you know', t, re.I) and '!' not in t)
out, rows, problems, stats = {}, [], [], {'ok': 0, 'fix': 0, 'drop': 0, 'unchecked': 0}
for code in sorted(facts):
    lst = []
    for i, e in enumerate(facts[code][:3], 1):
        c = checks.get(f'{code}#{i}')
        text, src, note = e['fact'], e.get('source', ''), e.get('checked', '')
        if not c: stats['unchecked'] += 1
        else:
            v = c.get('verdict', 'ok'); stats[v] = stats.get(v, 0) + 1
            if v in ('fix', 'drop') and c.get('fixed'):
                text = c['fixed']; note = c.get('evidence') or note
                m = re.search(r'https?://\S+', c.get('evidence') or '')
                if v == 'drop' and m: src = m.group(0).rstrip(').,;')
            elif v == 'drop': problems.append(f'{code}#{i}: dropped, no replacement'); continue
        text = text.strip()
        if not ok(text): problems.append(f'{code}#{i}: fails the rules: {text}'); continue
        if text in lst: problems.append(f'{code}#{i}: duplicate'); continue
        lst.append(text); rows.append((code, i, text, src, note))
    if lst: out[code] = lst
print(stats, len(out), 'types', sum(len(v) for v in out.values()), 'facts')
for p in problems: print('  !', p)
# js/sky-facts.js: replace TYPE_FACTS, keep the helpers below it
p = os.path.join(ROOT, 'js', 'sky-facts.js'); s = open(p).read()
head = s[:s.index('export const TYPE_FACTS = {')]; tail = s[s.index('};', s.index('export const TYPE_FACTS = {')) + 2:]
head = re.sub(r'^// Sky Collector: one checked fact per aircraft type.*?\n(?=export)', '', head, flags=re.S)
body = ',\n'.join(f'  {k}: [\n' + ',\n'.join('    ' + json.dumps(t, ensure_ascii=False) for t in v) + ',\n  ]' for k, v in out.items())
intro = ("// Sky Collector: three checked facts per aircraft type (ICAO type code), shown on plane cards (flight-card.js planeFact):\n"
         "// a new card shows the first; each different aircraft of the type you catch turns it to the next (typeFact(code, n)).\n"
         "// Each is 1-2 plain sentences with exactly one **bold** phrase (rendered by rich()), written to docs/FACT-STYLE.md and\n"
         "// checked by an independent fact-checker against its source (docs/FACTS-SOURCES.md). Generated by\n"
         "// scripts/facts/apply-type-facts.py; edit there or in the source table, not by hand. No imports, no DOM.\n")
open(p, 'w').write(head + intro + 'export const TYPE_FACTS = {\n' + body + ',\n};' + tail)
# docs/FACTS-SOURCES.md
md = ['# Sky facts: sources', '',
      'Three facts per aircraft-type card (`js/sky-facts.js`), written to `docs/FACT-STYLE.md` (2026-11-18). Each was checked by a',
      'writer-researcher and then independently by a fact-checker against the source below; "Checked" is what was read there.', '',
      '| Code | # | Fact | Source | Checked |', '|---|---|---|---|---|']
cell = lambda x: str(x).replace('|', '\\|').replace('\n', ' ')
for code, i, text, src, note in rows: md.append(f'| {code} | {i} | {cell(text)} | {cell(src)} | {cell(note)[:300]} |')
open(os.path.join(ROOT, 'docs', 'FACTS-SOURCES.md'), 'w').write('\n'.join(md) + '\n')
